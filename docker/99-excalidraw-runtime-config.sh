#!/bin/sh
# Runs from /docker-entrypoint.d/ before nginx starts.
#
# Generates <html>/runtime-config.js from environment variables, so the same
# image can be pointed at different collaboration/storage services without a
# rebuild:
#
#   EXCALIDRAW_COLLAB_URL         wss://collab.example.com
#   EXCALIDRAW_COLLAB_PATH        optional Socket.IO path, e.g. /whiteboard-socket.io/
#   EXCALIDRAW_BACKEND_URL        https://json.example.com
#   EXCALIDRAW_BACKEND_API_PREFIX optional, default /api/v2
#                                 e.g. /whiteboard-api/api/v2 to avoid clashing
#                                 with an existing /api/v2 on the same domain
#   EXCALIDRAW_BACKEND_GET_URL    optional, full read URL (overrides prefix)
#   EXCALIDRAW_BACKEND_POST_URL   optional, full write URL (overrides prefix)
#
set -eu

log() { echo "[excalidraw-runtime-config] $*"; }

HTML_DIR="${EXCALIDRAW_HTML_DIR:-/usr/share/nginx/html/whiteboard}"

if [ ! -d "$HTML_DIR" ]; then
  log "directory not found: $HTML_DIR (set EXCALIDRAW_HTML_DIR); skipping"
  exit 0
fi

COLLAB_URL="${EXCALIDRAW_COLLAB_URL:-}"
COLLAB_PATH="${EXCALIDRAW_COLLAB_PATH:-}"
BACKEND_BASE="${EXCALIDRAW_BACKEND_URL:-}"
BACKEND_API_PREFIX="${EXCALIDRAW_BACKEND_API_PREFIX:-/api/v2}"
BACKEND_GET="${EXCALIDRAW_BACKEND_GET_URL:-}"
BACKEND_POST="${EXCALIDRAW_BACKEND_POST_URL:-}"

# Normalize the API prefix to /something (no trailing slash).
case "$BACKEND_API_PREFIX" in
  /*) ;;
  *) BACKEND_API_PREFIX="/$BACKEND_API_PREFIX" ;;
esac
BACKEND_API_PREFIX="$(printf '%s' "$BACKEND_API_PREFIX" | sed 's:/*$::')"
[ -n "$BACKEND_API_PREFIX" ] || BACKEND_API_PREFIX="/api/v2"

# Excalidraw passes this URL to socket.io-client. A path in the URL is treated
# as a Socket.IO namespace (excalidraw-room only serves "/"), so keep the origin.
if [ -n "$COLLAB_URL" ]; then
  COLLAB_URL="$(printf '%s' "$COLLAB_URL" | sed 's:/*$::')"
  COLLAB_ORIGIN="$(printf '%s' "$COLLAB_URL" | sed 's#^\([a-zA-Z][a-zA-Z0-9+.-]*://[^/]*\).*#\1#')"
  if [ "$COLLAB_ORIGIN" != "$COLLAB_URL" ]; then
    log "WARNING: path in EXCALIDRAW_COLLAB_URL is treated as a Socket.IO namespace; using $COLLAB_ORIGIN"
    COLLAB_URL="$COLLAB_ORIGIN"
  fi
fi

if [ -n "$COLLAB_PATH" ]; then
  case "$COLLAB_PATH" in
    /*) ;;
    *) COLLAB_PATH="/$COLLAB_PATH" ;;
  esac
  COLLAB_PATH="$(printf '%s' "$COLLAB_PATH" | sed 's:/*$::')/"
fi

if [ -n "$BACKEND_BASE" ]; then
  BACKEND_BASE="$(printf '%s' "$BACKEND_BASE" | sed 's:/*$::')"
fi

if [ -z "$BACKEND_GET" ] && [ -n "$BACKEND_BASE" ]; then
  case "$BACKEND_BASE" in
    *"$BACKEND_API_PREFIX") BACKEND_GET="$BACKEND_BASE/" ;;
    *) BACKEND_GET="$BACKEND_BASE$BACKEND_API_PREFIX/" ;;
  esac
fi

if [ -z "$BACKEND_POST" ] && [ -n "$BACKEND_GET" ]; then
  case "$BACKEND_GET" in
    */post/) BACKEND_POST="$BACKEND_GET" ;;
    *) BACKEND_POST="${BACKEND_GET%/}/post/" ;;
  esac
fi

if [ -z "$BACKEND_GET" ] && [ -n "$BACKEND_POST" ]; then
  BACKEND_GET="$(printf '%s' "$BACKEND_POST" | sed 's:post/*$::')"
fi

escape_js() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

FIELDS=""
add_field() {
  key="$1"
  value="$2"
  [ -n "$value" ] || return 0
  escaped="$(escape_js "$value")"
  if [ -z "$FIELDS" ]; then
    FIELDS="\"$key\":\"$escaped\""
  else
    FIELDS="$FIELDS,\"$key\":\"$escaped\""
  fi
}

add_field collabUrl "$COLLAB_URL"
add_field collabPath "$COLLAB_PATH"
add_field backendGetUrl "$BACKEND_GET"
add_field backendPostUrl "$BACKEND_POST"

cat > "$HTML_DIR/runtime-config.js" <<EOF
/* Generated by 99-excalidraw-runtime-config.sh at container start. */
window.__EXCALIDRAW_ENV__ = {${FIELDS}};
EOF

log "collab=${COLLAB_URL:-<build-time>} collabPath=${COLLAB_PATH:-<default>} backendGet=${BACKEND_GET:-<build-time>} backendPost=${BACKEND_POST:-<build-time>}"